"""Shared test fixtures: a synthetic speech clip and the speech model.

Speech is generated by the OS's own text-to-speech (espeak-ng on Linux, SAPI on Windows), so tests need no
recordings checked in. Tests that need it are skipped when neither is available.
"""
import os
import subprocess
import sys
import wave

import numpy as np
import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

SENTENCE = "Hi Priya, thanks for sending the quarterly report yesterday."


def _espeak(text, path):
    import array
    import ctypes

    lib = ctypes.CDLL("libespeak-ng.so.1")
    cb_type = ctypes.CFUNCTYPE(ctypes.c_int, ctypes.POINTER(ctypes.c_short), ctypes.c_int, ctypes.c_void_p)
    buf = array.array("h")

    @cb_type
    def cb(wav, n, ev):
        if wav and n > 0:
            buf.extend(wav[:n])
        return 0

    rate = lib.espeak_Initialize(1, 500, None, 0)
    lib.espeak_SetSynthCallback(cb)
    lib.espeak_SetVoiceByName(b"en-us")
    lib.espeak_SetParameter(1, 150, 0)
    t = text.encode()
    lib.espeak_Synth(t, len(t) + 1, 0, 0, 0, 0, None, None)
    lib.espeak_Synchronize()
    with wave.open(path, "wb") as w:
        w.setnchannels(1), w.setsampwidth(2), w.setframerate(rate), w.writeframes(buf.tobytes())


def _sapi(text, path):
    script = (
        "Add-Type -AssemblyName System.Speech; "
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer; "
        f"$s.SetOutputToWaveFile('{path}'); $s.Speak('{text}'); $s.Dispose()"
    )
    subprocess.run(["powershell", "-NoProfile", "-Command", script], check=True, timeout=60)


def to_16k_float(path):
    with wave.open(path) as w:
        rate, ch, width = w.getframerate(), w.getnchannels(), w.getsampwidth()
        raw = w.readframes(w.getnframes())
    a = np.frombuffer(raw, dtype=np.int16 if width == 2 else np.uint8).astype(np.float32)
    a = a / 32768.0 if width == 2 else (a - 128) / 128.0
    if ch > 1:
        a = a.reshape(-1, ch).mean(axis=1)
    return np.interp(np.arange(0, len(a), rate / 16000), np.arange(len(a)), a).astype(np.float32)


@pytest.fixture(scope="session")
def speech(tmp_path_factory):
    """16 kHz float32 audio of SENTENCE, with 0.5 s of silence after it."""
    path = str(tmp_path_factory.mktemp("speech") / "speech.wav")
    try:
        (_sapi if sys.platform == "win32" else _espeak)(SENTENCE, path)
    except Exception as ex:
        pytest.skip(f"no text-to-speech available: {ex}")
    return np.concatenate([to_16k_float(path), np.zeros(8000, np.float32)])


